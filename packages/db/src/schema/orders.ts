import { sql } from "drizzle-orm";
import {
  bigint,
  check,
  foreignKey,
  index,
  integer,
  primaryKey,
  text,
  unique,
  uuid,
} from "drizzle-orm/pg-core";
import { app } from "./app-schema.ts";
import { internalId, publicRef, timestamptz, timestamptzNow } from "./common.ts";
import { businessProfiles } from "./identity.ts";
import { karaokeSlots } from "./karaoke.ts";
import { entryTicketOfferings, goods } from "./sales.ts";

// SPEC-100 §16 `app.orders`, §17 `app.order_items` and §18 `app.entry_sales_allocations` (Part V Order /
// Allocation). These declarations exist for types and queries; the DDL source of truth is
// migrations/0006_orders_payments.sql (SPEC-100 §57, DB-MIG-002). Every constraint carries its explicit name
// (DB-ARC-007) and the SQL text equals the migration's. State and Purpose names are SPEC-030's (DB-STA-001); the
// DB CHECK guards the allowed values and the repository guards transitions with conditional updates (DB-STA-002).

export const orders = app.table(
  "orders",
  {
    id: internalId(),
    publicRef: publicRef(),
    purchaseCauseKey: uuid("purchase_cause_key").notNull(),
    customerProfileId: bigint("customer_profile_id", { mode: "bigint" }).notNull(),
    purpose: text("purpose")
      .$type<
        "ENTRY_TICKET_PURCHASE" | "KARAOKE_PURCHASE" | "GOODS_PURCHASE" | "ENTRY_GOODS_PURCHASE"
      >()
      .notNull(),
    state: text("state")
      .$type<
        | "PREPARED"
        | "AWAITING_PAYMENT"
        | "CONFIRMED"
        | "PAYMENT_FAILED"
        | "CANCELED"
        | "EXPIRED"
        | "REVIEW_REQUIRED"
      >()
      .notNull(),
    currency: text("currency").notNull(),
    totalAmount: bigint("total_amount", { mode: "bigint" }).notNull(),
    confirmedAt: timestamptz("confirmed_at"),
    terminalAt: timestamptz("terminal_at"),
    createdAt: timestamptzNow("created_at"),
    updatedAt: timestamptzNow("updated_at"),
  },
  (t) => [
    primaryKey({ name: "pk_orders", columns: [t.id] }),
    unique("uq_orders_public_ref").on(t.publicRef),
    unique("uq_orders_purchase_cause_key").on(t.purchaseCauseKey),
    // Composite foreign key targets of Order Items, Karaoke Holds / Reservations and Goods (SPEC-100 §16).
    unique("uq_orders_id_purpose").on(t.id, t.purpose),
    unique("uq_orders_id_purpose_currency").on(t.id, t.purpose, t.currency),
    unique("uq_orders_id_customer_profile_id").on(t.id, t.customerProfileId),
    foreignKey({
      name: "fk_orders_customer_profile",
      columns: [t.customerProfileId],
      foreignColumns: [businessProfiles.id],
    }).onDelete("restrict"),
    check(
      "ck_orders_purpose",
      sql`${t.purpose} IN ('ENTRY_TICKET_PURCHASE','KARAOKE_PURCHASE','GOODS_PURCHASE','ENTRY_GOODS_PURCHASE')`,
    ),
    check(
      "ck_orders_state",
      sql`${t.state} IN ('PREPARED','AWAITING_PAYMENT','CONFIRMED','PAYMENT_FAILED','CANCELED','EXPIRED','REVIEW_REQUIRED')`,
    ),
    check(
      "ck_orders_currency",
      sql`${t.currency} = upper(${t.currency}) AND ${t.currency} ~ '^[A-Z]{3}$'`,
    ),
    check("ck_orders_total_amount", sql`${t.totalAmount} >= 0`),
    check(
      "ck_orders_confirmed_at",
      sql`(${t.state} = 'CONFIRMED') = (${t.confirmedAt} IS NOT NULL)`,
    ),
    check(
      "ck_orders_terminal_at",
      sql`${t.state} NOT IN ('PAYMENT_FAILED','CANCELED','EXPIRED') OR ${t.terminalAt} IS NOT NULL`,
    ),
    index("ix_orders_customer_created").on(t.customerProfileId, t.createdAt.desc()),
    index("ix_orders_admin_state_created").on(t.state, t.createdAt.desc()),
    index("ix_orders_admin_purpose_created").on(t.purpose, t.createdAt.desc()),
  ],
);

export const orderItems = app.table(
  "order_items",
  {
    id: internalId(),
    orderId: bigint("order_id", { mode: "bigint" }).notNull(),
    purpose: text("purpose")
      .$type<
        "ENTRY_TICKET_PURCHASE" | "KARAOKE_PURCHASE" | "GOODS_PURCHASE" | "ENTRY_GOODS_PURCHASE"
      >()
      .notNull(),
    lineNo: integer("line_no").notNull(),
    quantity: integer("quantity").notNull(),
    unitAmount: bigint("unit_amount", { mode: "bigint" }).notNull(),
    currency: text("currency").notNull(),
    // SPEC-100 §9 / DB-MNY-001: generated by the database; never written by the repository.
    lineTotalAmount: bigint("line_total_amount", { mode: "bigint" }).generatedAlwaysAs(
      sql`unit_amount * quantity::bigint`,
    ),
    itemNameSnapshot: text("item_name_snapshot").notNull(),
    entryOfferingId: bigint("entry_offering_id", { mode: "bigint" }),
    karaokeSlotId: bigint("karaoke_slot_id", { mode: "bigint" }),
    goodsId: bigint("goods_id", { mode: "bigint" }),
    createdAt: timestamptzNow("created_at"),
  },
  (t) => [
    primaryKey({ name: "pk_order_items", columns: [t.id] }),
    unique("uq_order_items_order_id_line_no").on(t.orderId, t.lineNo),
    // Composite foreign key targets of Allocations, Holds, Tickets and Goods fulfilment (SPEC-100 §17).
    unique("uq_order_items_id_order_id").on(t.id, t.orderId),
    unique("uq_order_items_id_purpose").on(t.id, t.purpose),
    unique("uq_order_items_id_order_id_purpose").on(t.id, t.orderId, t.purpose),
    unique("uq_order_items_id_order_id_purpose_karaoke_slot_id").on(
      t.id,
      t.orderId,
      t.purpose,
      t.karaokeSlotId,
    ),
    unique("uq_order_items_id_entry_offering_id").on(t.id, t.entryOfferingId),
    unique("uq_order_items_id_goods_id").on(t.id, t.goodsId),
    // DB-ORD-004: the item repeats its Order's purpose and currency.
    foreignKey({
      name: "fk_order_items_order",
      columns: [t.orderId, t.purpose, t.currency],
      foreignColumns: [orders.id, orders.purpose, orders.currency],
    }).onDelete("restrict"),
    foreignKey({
      name: "fk_order_items_entry_offering",
      columns: [t.entryOfferingId],
      foreignColumns: [entryTicketOfferings.id],
    }).onDelete("restrict"),
    foreignKey({
      name: "fk_order_items_karaoke_slot",
      columns: [t.karaokeSlotId],
      foreignColumns: [karaokeSlots.id],
    }).onDelete("restrict"),
    foreignKey({
      name: "fk_order_items_goods",
      columns: [t.goodsId],
      foreignColumns: [goods.id],
    }).onDelete("restrict"),
    check("ck_order_items_line_no", sql`${t.lineNo} > 0`),
    check("ck_order_items_quantity", sql`${t.quantity} > 0`),
    check("ck_order_items_unit_amount", sql`${t.unitAmount} >= 0`),
    check(
      "ck_order_items_currency",
      sql`${t.currency} = upper(${t.currency}) AND ${t.currency} ~ '^[A-Z]{3}$'`,
    ),
    // DB-ORD-002 / DB-ORD-004: the Purpose / purchase source exclusivity of SPEC-100 §17.
    check(
      "ck_order_items_source",
      sql`(${t.purpose} = 'ENTRY_TICKET_PURCHASE' AND ${t.entryOfferingId} IS NOT NULL AND ${t.karaokeSlotId} IS NULL AND ${t.goodsId} IS NULL) OR (${t.purpose} = 'KARAOKE_PURCHASE' AND ${t.entryOfferingId} IS NULL AND ${t.karaokeSlotId} IS NOT NULL AND ${t.goodsId} IS NULL AND ${t.quantity} = 1) OR (${t.purpose} = 'GOODS_PURCHASE' AND ${t.entryOfferingId} IS NULL AND ${t.karaokeSlotId} IS NULL AND ${t.goodsId} IS NOT NULL) OR (${t.purpose} = 'ENTRY_GOODS_PURCHASE' AND ${t.karaokeSlotId} IS NULL AND ((${t.entryOfferingId} IS NOT NULL AND ${t.goodsId} IS NULL) OR (${t.entryOfferingId} IS NULL AND ${t.goodsId} IS NOT NULL)))`,
    ),
  ],
);

export const entrySalesAllocations = app.table(
  "entry_sales_allocations",
  {
    id: internalId(),
    orderItemId: bigint("order_item_id", { mode: "bigint" }).notNull(),
    orderId: bigint("order_id", { mode: "bigint" }).notNull(),
    purpose: text("purpose").$type<"ENTRY_TICKET_PURCHASE" | "ENTRY_GOODS_PURCHASE">().notNull(),
    offeringId: bigint("offering_id", { mode: "bigint" }).notNull(),
    quantity: integer("quantity").notNull(),
    state: text("state").$type<"HELD" | "COMMITTED" | "RELEASED">().notNull(),
    heldAt: timestamptzNow("held_at"),
    committedAt: timestamptz("committed_at"),
    releasedAt: timestamptz("released_at"),
  },
  (t) => [
    primaryKey({ name: "pk_entry_sales_allocations", columns: [t.id] }),
    unique("uq_entry_sales_allocations_order_item_id").on(t.orderItemId),
    foreignKey({
      name: "fk_entry_sales_allocations_order_item",
      columns: [t.orderItemId, t.orderId, t.purpose],
      foreignColumns: [orderItems.id, orderItems.orderId, orderItems.purpose],
    }).onDelete("restrict"),
    foreignKey({
      name: "fk_entry_sales_allocations_offering",
      columns: [t.orderItemId, t.offeringId],
      foreignColumns: [orderItems.id, orderItems.entryOfferingId],
    }).onDelete("restrict"),
    check(
      "ck_entry_sales_allocations_purpose",
      sql`${t.purpose} IN ('ENTRY_TICKET_PURCHASE','ENTRY_GOODS_PURCHASE')`,
    ),
    check("ck_entry_sales_allocations_quantity", sql`${t.quantity} > 0`),
    check("ck_entry_sales_allocations_state", sql`${t.state} IN ('HELD','COMMITTED','RELEASED')`),
    check(
      "ck_entry_sales_allocations_state_times",
      sql`(${t.state} = 'HELD' AND ${t.committedAt} IS NULL AND ${t.releasedAt} IS NULL) OR (${t.state} = 'COMMITTED' AND ${t.committedAt} IS NOT NULL AND ${t.releasedAt} IS NULL) OR (${t.state} = 'RELEASED' AND ${t.releasedAt} IS NOT NULL AND ${t.committedAt} IS NULL)`,
    ),
    index("ix_entry_allocations_offering_state").on(t.offeringId, t.state),
  ],
);
