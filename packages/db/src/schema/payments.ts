// SPEC-100 §20 `app.checkout_attempts`, §21 `app.payment_bindings`, §22 `app.webhook_receipts` and §23
// `app.refund_records` (Part VI Payment Persistence). These declarations exist for types and queries; the DDL
// source of truth is migrations/0006_orders_payments.sql (SPEC-100 §57, DB-MIG-002). Every constraint carries its
// explicit name (DB-ARC-007) and the SQL text equals the migration's. creation_result and processing_state are
// processing results, not Domain States (SPEC-100 §10, §20); the Refund states are SPEC-070 §37's.

/** `bytea`, read and written as a `Uint8Array` (SPEC-100 §56). */
const bytea = customType<{ data: Uint8Array; driverData: Buffer }>({
  dataType: () => "bytea",
  toDriver: (value) => Buffer.from(value),
  fromDriver: (value) => new Uint8Array(value),
});

export const checkoutAttempts = app.table(
  "checkout_attempts",
  {
    id: internalId(),
    publicRef: publicRef(),
    orderId: bigint("order_id", { mode: "bigint" }).notNull(),
    attemptNo: integer("attempt_no").notNull(),
    stripeIdempotencyKey: text("stripe_idempotency_key").notNull(),
    creationResult: text("creation_result")
      .$type<"PENDING" | "SUCCEEDED" | "FAILED" | "UNKNOWN">()
      .notNull(),
    providerRequestStartedAt: timestamptz("provider_request_started_at"),
    providerResponseAt: timestamptz("provider_response_at"),
    lastErrorCode: text("last_error_code"),
    createdAt: timestamptzNow("created_at"),
    updatedAt: timestamptzNow("updated_at"),
  },
  (t) => [
    primaryKey({ name: "pk_checkout_attempts", columns: [t.id] }),
    unique("uq_checkout_attempts_public_ref").on(t.publicRef),
    // DB-PAY-001: a retry reuses the attempt and its Stripe idempotency key.
    unique("uq_checkout_attempts_stripe_idempotency_key").on(t.stripeIdempotencyKey),
    unique("uq_checkout_attempts_order_id_attempt_no").on(t.orderId, t.attemptNo),
    // The target of the Payment Binding composite foreign key (SPEC-100 §21).
    unique("uq_checkout_attempts_id_order_id").on(t.id, t.orderId),
    foreignKey({
      name: "fk_checkout_attempts_order",
      columns: [t.orderId],
      foreignColumns: [orders.id],
    }).onDelete("restrict"),
    check("ck_checkout_attempts_attempt_no", sql`${t.attemptNo} > 0`),
    check(
      "ck_checkout_attempts_creation_result",
      sql`${t.creationResult} IN ('PENDING','SUCCEEDED','FAILED','UNKNOWN')`,
    ),
    // SPEC-100 §45.2 names this index although uq_checkout_attempts_order_id_attempt_no covers the same columns.
    index("ix_checkout_attempts_order_attempt").on(t.orderId, t.attemptNo.desc()),
  ],
);

export const paymentBindings = app.table(
  "payment_bindings",
  {
    id: internalId(),
    orderId: bigint("order_id", { mode: "bigint" }).notNull(),
    checkoutAttemptId: bigint("checkout_attempt_id", { mode: "bigint" }).notNull(),
    stripeCheckoutSessionId: text("stripe_checkout_session_id").notNull(),
    stripePaymentIntentId: text("stripe_payment_intent_id"),
    stripeChargeId: text("stripe_charge_id"),
    checkoutSessionCreatedAt: timestamptz("checkout_session_created_at").notNull(),
    // SPEC-100 §21 / §67 item 24 / UCR-100-006: Session creation + 30 minutes, generated by the database. The sum
    // is taken in UTC because timestamptz + interval is STABLE and a generated column needs an IMMUTABLE expression.
    paymentDeadlineAt: timestamptz("payment_deadline_at").generatedAlwaysAs(
      sql`((checkout_session_created_at AT TIME ZONE 'UTC') + interval '30 minutes') AT TIME ZONE 'UTC'`,
    ),
    paymentCompletedAt: timestamptz("payment_completed_at"),
    amountTotal: bigint("amount_total", { mode: "bigint" }).notNull(),
    currency: text("currency").notNull(),
    isActive: boolean("is_active").notNull().default(true),
    boundAt: timestamptzNow("bound_at"),
    deactivatedAt: timestamptz("deactivated_at"),
    stripeReceiptUrl: text("stripe_receipt_url"),
  },
  (t) => [
    primaryKey({ name: "pk_payment_bindings", columns: [t.id] }),
    // DB-PAY-002: no Stripe object binds to two Orders, and an Attempt binds once.
    unique("uq_payment_bindings_checkout_attempt_id").on(t.checkoutAttemptId),
    unique("uq_payment_bindings_stripe_checkout_session_id").on(t.stripeCheckoutSessionId),
    unique("uq_payment_bindings_stripe_payment_intent_id").on(t.stripePaymentIntentId),
    unique("uq_payment_bindings_stripe_charge_id").on(t.stripeChargeId),
    foreignKey({
      name: "fk_payment_bindings_order",
      columns: [t.orderId],
      foreignColumns: [orders.id],
    }).onDelete("restrict"),
    foreignKey({
      name: "fk_payment_bindings_checkout_attempt",
      columns: [t.checkoutAttemptId, t.orderId],
      foreignColumns: [checkoutAttempts.id, checkoutAttempts.orderId],
    }).onDelete("restrict"),
    check("ck_payment_bindings_amount_total", sql`${t.amountTotal} >= 0`),
    check(
      "ck_payment_bindings_currency",
      sql`${t.currency} = upper(${t.currency}) AND ${t.currency} ~ '^[A-Z]{3}$'`,
    ),
    check("ck_payment_bindings_active", sql`${t.isActive} = (${t.deactivatedAt} IS NULL)`),
    index("ix_payment_bindings_order_bound").on(t.orderId, t.boundAt.desc()),
    // DB-PAY-003: at most one active Checkout per Order.
    uniqueIndex("ux_payment_bindings_order_active").on(t.orderId).where(sql`${t.isActive}`),
  ],
);

export const webhookReceipts = app.table(
  "webhook_receipts",
  {
    id: internalId(),
    stripeEventId: text("stripe_event_id").notNull(),
    eventType: text("event_type").notNull(),
    stripeObjectId: text("stripe_object_id"),
    stripeAccountId: text("stripe_account_id"),
    livemode: boolean("livemode").notNull(),
    processingState: text("processing_state")
      .$type<"RECEIVED" | "PROCESSED" | "IGNORED" | "FAILED_RETRYABLE" | "REVIEW_REQUIRED">()
      .notNull(),
    payloadSha256: bytea("payload_sha256").notNull(),
    // SPEC-100 §22 / §56: a minimal snapshot, validated at the repository boundary before use.
    canonicalSnapshot: jsonb("canonical_snapshot").$type<unknown>().notNull(),
    receivedAt: timestamptzNow("received_at"),
    processedAt: timestamptz("processed_at"),
    lastErrorCode: text("last_error_code"),
    updatedAt: timestamptzNow("updated_at"),
  },
  (t) => [
    primaryKey({ name: "pk_webhook_receipts", columns: [t.id] }),
    // PAY-WHK-007 / SEC-PAY-008: one receipt per Stripe Event ID.
    unique("uq_webhook_receipts_stripe_event_id").on(t.stripeEventId),
    check(
      "ck_webhook_receipts_processing_state",
      sql`${t.processingState} IN ('RECEIVED','PROCESSED','IGNORED','FAILED_RETRYABLE','REVIEW_REQUIRED')`,
    ),
    check("ck_webhook_receipts_payload_sha256", sql`octet_length(${t.payloadSha256}) = 32`),
    index("ix_webhook_receipts_retry")
      .on(t.receivedAt)
      .where(sql`${t.processingState} IN ('FAILED_RETRYABLE','REVIEW_REQUIRED')`),
  ],
);

export const refundRecords = app.table(
  "refund_records",
  {
    id: internalId(),
    orderId: bigint("order_id", { mode: "bigint" }).notNull(),
    businessCauseKey: uuid("business_cause_key").notNull(),
    stripeIdempotencyKey: text("stripe_idempotency_key").notNull(),
    stripeRefundId: text("stripe_refund_id"),
    state: text("state")
      .$type<"REQUESTED" | "PENDING" | "SUCCEEDED" | "FAILED" | "REVIEW_REQUIRED">()
      .notNull(),
    requestedAmount: bigint("requested_amount", { mode: "bigint" }).notNull(),
    currency: text("currency").notNull(),
    isFullRefund: boolean("is_full_refund").notNull(),
    requestedByProfileId: bigint("requested_by_profile_id", { mode: "bigint" }).notNull(),
    requestedAt: timestamptzNow("requested_at"),
    providerUpdatedAt: timestamptz("provider_updated_at"),
    succeededAt: timestamptz("succeeded_at"),
    failedAt: timestamptz("failed_at"),
    updatedAt: timestamptzNow("updated_at"),
  },
  (t) => [
    primaryKey({ name: "pk_refund_records", columns: [t.id] }),
    unique("uq_refund_records_business_cause_key").on(t.businessCauseKey),
    unique("uq_refund_records_stripe_idempotency_key").on(t.stripeIdempotencyKey),
    unique("uq_refund_records_stripe_refund_id").on(t.stripeRefundId),
    foreignKey({
      name: "fk_refund_records_order",
      columns: [t.orderId],
      foreignColumns: [orders.id],
    }).onDelete("restrict"),
    foreignKey({
      name: "fk_refund_records_requested_by_profile",
      columns: [t.requestedByProfileId],
      foreignColumns: [businessProfiles.id],
    }).onDelete("restrict"),
    check(
      "ck_refund_records_state",
      sql`${t.state} IN ('REQUESTED','PENDING','SUCCEEDED','FAILED','REVIEW_REQUIRED')`,
    ),
    check("ck_refund_records_requested_amount", sql`${t.requestedAmount} > 0`),
    check(
      "ck_refund_records_currency",
      sql`${t.currency} = upper(${t.currency}) AND ${t.currency} ~ '^[A-Z]{3}$'`,
    ),
    // SPEC-100 §23: at most one live or succeeded full refund per Order.
    uniqueIndex("ux_refund_records_order_live_full")
      .on(t.orderId)
      .where(
        sql`${t.isFullRefund} AND ${t.state} IN ('REQUESTED','PENDING','SUCCEEDED','REVIEW_REQUIRED')`,
      ),
  ],
);
